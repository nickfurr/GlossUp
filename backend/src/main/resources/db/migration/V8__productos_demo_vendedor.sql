DECLARE
    v_vendedor BIGINT;
BEGIN
    IF EXISTS (SELECT 1 FROM semilla_composicion c WHERE NOT EXISTS (SELECT 1 FROM ingrediente i WHERE i.nombre_inci = c.inci)) THEN
        RAISE EXCEPTION 'Producto demo con un ingrediente que no está en el catálogo';
    END IF;

    SELECT id INTO v_vendedor FROM usuario WHERE lower(email) = 'manuel.pinedave@uqvirtual.edu.co';
    IF v_vendedor IS NULL THEN
        RAISE NOTICE 'Vendedor demo no existe: no se siembran productos';
        RETURN;
    END IF;

    CREATE TEMP TABLE producto_nuevo (id BIGINT, clave INT) ON COMMIT DROP;
    WITH insertados AS (
        INSERT INTO producto (vendedor_id, nombre, marca, categoria, precio, stock, ph, activo)
        SELECT v_vendedor, s.nombre, s.marca, s.categoria, s.precio, s.stock, s.ph, TRUE
        FROM semilla_producto s
        WHERE NOT EXISTS (SELECT 1 FROM producto p WHERE p.vendedor_id = v_vendedor AND p.nombre = s.nombre)
        RETURNING id, nombre
    )
    INSERT INTO producto_nuevo SELECT i.id, s.clave FROM insertados i JOIN semilla_producto s ON s.nombre = i.nombre;

    INSERT INTO producto_imagen (producto_id, url, orden)
    SELECT n.id, s.imagen, 0 FROM producto_nuevo n JOIN semilla_producto s ON s.clave = n.clave;

    INSERT INTO producto_ingrediente (producto_id, ingrediente_id)
    SELECT n.id, i.id
    FROM producto_nuevo n
    JOIN semilla_composicion c ON c.clave = n.clave
    JOIN ingrediente i ON i.nombre_inci = c.inci;
END $$;
